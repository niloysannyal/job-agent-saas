#!/usr/bin/env python
"""
Git Pre-Commit Hook Installer — Job Application Agent SaaS
Adapted from ECC's install-hooks / codex-git-hooks pattern.
Configures .git/hooks/pre-commit to automatically enforce the 5-phase verification loop.
"""
import sys
import os
from pathlib import Path

# Enable UTF-8 console output if possible
if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass

ROOT = Path(__file__).resolve().parent.parent
HOOKS_DIR = ROOT / ".git" / "hooks"
PRE_COMMIT_FILE = HOOKS_DIR / "pre-commit"

HOOK_SCRIPT = """#!/usr/bin/env sh
# Job Application Agent SaaS — Pre-Commit Quality Gate
# Automatically generated by scripts/install_hooks.py

echo "=== Running Pre-Commit Verification Gate ==="
python scripts/verify.py --quick
VERIFY_EXIT=$?

if [ $VERIFY_EXIT -ne 0 ]; then
  echo ""
  echo "[BLOCKED] Pre-commit verification failed! Please resolve errors before committing."
  exit 1
fi

python scripts/review.py
REVIEW_EXIT=$?

if [ $REVIEW_EXIT -ne 0 ]; then
  echo ""
  echo "[BLOCKED] Code quality review failed! Resolve CRITICAL/HIGH findings before committing."
  exit 1
fi

echo "=== Pre-Commit Verification Passed! Proceeding with commit. ==="
exit 0
"""

def install_hook():
    print("=" * 65)
    print("  Job Application Agent SaaS -- Git Hook Setup")
    print("=" * 65)

    if not (ROOT / ".git").exists():
        print("[FAIL] .git directory not found.")
        return 1

    HOOKS_DIR.mkdir(parents=True, exist_ok=True)
    PRE_COMMIT_FILE.write_text(HOOK_SCRIPT, encoding="utf-8", newline="\n")

    # On POSIX, ensure executable permission
    if os.name != "nt":
        import stat
        PRE_COMMIT_FILE.chmod(PRE_COMMIT_FILE.stat().st_mode | stat.S_IEXEC)

    print(f"[PASS] Pre-commit hook installed to: {PRE_COMMIT_FILE}")
    print("  Every commit will now automatically be verified against the 5-phase quality loop.")
    print("=" * 65)
    return 0

if __name__ == "__main__":
    sys.exit(install_hook())

